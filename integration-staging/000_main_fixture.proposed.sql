DO $$
BEGIN
  IF current_database() <> 'examflow_main_staging' THEN
    RAISE EXCEPTION 'Refusing a non-staging main database';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_tables WHERE schemaname='public') THEN
    RAISE EXCEPTION 'Expected empty main fixture; inspect before proceeding';
  END IF;
END $$;
CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  keycloak_user_id varchar(255),
  username varchar(255) NOT NULL UNIQUE,
  password_hash varchar(255),
  role varchar(255) NOT NULL CHECK (role IN ('teacher','student')),
  email varchar(255) NOT NULL UNIQUE,
  full_name varchar(255) NOT NULL,
  department varchar(255),
  student_class_id bigint,
  status varchar(255) NOT NULL DEFAULT 'active',
  auth_failed_attempts integer NOT NULL DEFAULT 0,
  auth_locked_until timestamptz,
  updated_at timestamp,
  photo_bucket varchar(255),
  photo_key varchar(255)
);
CREATE TABLE public.auth_sessions (
  id varchar(36) PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id),
  access_hash varchar(64) NOT NULL UNIQUE,
  refresh_hash varchar(64) NOT NULL UNIQUE,
  access_expires_at timestamptz NOT NULL,
  refresh_expires_at timestamptz NOT NULL
);
CREATE TABLE public.courses (
  id bigint PRIMARY KEY,
  code varchar(80) NOT NULL UNIQUE,
  name varchar(255) NOT NULL,
  created_by bigint NOT NULL REFERENCES public.users(id)
);
CREATE TABLE public.course_faculties (
  course_id bigint NOT NULL REFERENCES public.courses(id),
  faculty_id bigint NOT NULL REFERENCES public.users(id),
  PRIMARY KEY(course_id,faculty_id)
);
