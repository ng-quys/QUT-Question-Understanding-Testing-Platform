-- Additive baseline; also safe after the SQL already run manually in Supabase.
BEGIN;
CREATE TABLE IF NOT EXISTS public.student_classes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL,
 department VARCHAR(200), status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK(status IN ('active','inactive')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.exam_rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK(status IN ('active','inactive')),
 created_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.exam_room_students (
 room_id BIGINT NOT NULL REFERENCES public.exam_rooms(id) ON DELETE CASCADE,
 student_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
 added_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
 added_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), PRIMARY KEY(room_id,student_id)
);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS student_class_id BIGINT REFERENCES public.student_classes(id) ON DELETE SET NULL;
ALTER TABLE public.exam_sessions ADD COLUMN IF NOT EXISTS room_id BIGINT REFERENCES public.exam_rooms(id) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS idx_users_student_class_id ON public.users(student_class_id);
CREATE INDEX IF NOT EXISTS idx_exam_sessions_room_id ON public.exam_sessions(room_id);
CREATE INDEX IF NOT EXISTS idx_exam_room_students_student_id ON public.exam_room_students(student_id);
ALTER TABLE public.student_classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_room_students ENABLE ROW LEVEL SECURITY;
COMMIT;
