-- One sitting, common time window, groups allocated from a department. Run after 012.
BEGIN;
CREATE TABLE IF NOT EXISTS public.exam_sittings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id UUID NOT NULL UNIQUE, request_hash VARCHAR(64) NOT NULL,
 period_id BIGINT NOT NULL REFERENCES public.exam_periods(id) ON DELETE RESTRICT,
 course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE RESTRICT,
 department VARCHAR(200) NOT NULL, name VARCHAR(160) NOT NULL,
 start_time TIMESTAMP NOT NULL, end_time TIMESTAMP NOT NULL CHECK(end_time>start_time),
 students_per_group INTEGER NOT NULL CHECK(students_per_group BETWEEN 1 AND 1000),
 created_by BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.exam_sitting_groups (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sitting_id BIGINT NOT NULL REFERENCES public.exam_sittings(id) ON DELETE RESTRICT,
 group_number INTEGER NOT NULL CHECK(group_number>0),
 room_id BIGINT REFERENCES public.exam_rooms(id) ON DELETE RESTRICT,
 teacher_id BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
 exam_id BIGINT REFERENCES public.exams(id) ON DELETE RESTRICT,
 session_id BIGINT UNIQUE REFERENCES public.exam_sessions(id) ON DELETE RESTRICT,
 status VARCHAR(20) NOT NULL DEFAULT 'scheduled' CHECK(status IN ('scheduled','cancelled')),
 UNIQUE(sitting_id,group_number)
);
CREATE TABLE IF NOT EXISTS public.exam_sitting_students (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id BIGINT NOT NULL REFERENCES public.exam_sitting_groups(id) ON DELETE RESTRICT,
 period_id BIGINT NOT NULL REFERENCES public.exam_periods(id) ON DELETE RESTRICT,
 course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE RESTRICT,
 student_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
 position INTEGER NOT NULL CHECK(position>0), released_at TIMESTAMPTZ,
 UNIQUE(group_id,student_id), UNIQUE(group_id,position)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_sitting_student_once ON public.exam_sitting_students(period_id,course_id,student_id) WHERE released_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_sitting_students_student ON public.exam_sitting_students(student_id);
CREATE INDEX IF NOT EXISTS idx_sitting_groups_room ON public.exam_sitting_groups(room_id);
CREATE INDEX IF NOT EXISTS idx_sitting_groups_teacher ON public.exam_sitting_groups(teacher_id);
CREATE OR REPLACE FUNCTION public.release_cancelled_sitting_students() RETURNS TRIGGER LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 IF NEW.status='cancelled' AND OLD.status IS DISTINCT FROM NEW.status THEN
  UPDATE public.exam_sitting_groups SET status='cancelled' WHERE session_id=NEW.id;
  UPDATE public.exam_sitting_students rs SET released_at=NOW()
   FROM public.exam_sitting_groups g WHERE rs.group_id=g.id AND g.session_id=NEW.id AND rs.released_at IS NULL
   AND NOT EXISTS(SELECT 1 FROM public.exam_attempts a WHERE a.exam_session_id=NEW.id AND a.student_id=rs.student_id);
 END IF;
 RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS release_cancelled_sitting_students ON public.exam_sessions;
CREATE TRIGGER release_cancelled_sitting_students AFTER UPDATE OF status ON public.exam_sessions FOR EACH ROW EXECUTE FUNCTION public.release_cancelled_sitting_students();
ALTER TABLE public.exam_sittings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_sitting_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_sitting_students ENABLE ROW LEVEL SECURITY;
COMMIT;
