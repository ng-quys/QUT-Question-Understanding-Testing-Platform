-- Minimal foundation for department-based exam sittings (013).
-- No course enrollment or sequential-session allocation tables are created.
-- Existing data from an earlier version is deliberately not deleted.
BEGIN;

ALTER TABLE public.exam_rooms
 ADD COLUMN IF NOT EXISTS capacity INTEGER NOT NULL DEFAULT 40
 CHECK (capacity BETWEEN 1 AND 1000);

CREATE TABLE IF NOT EXISTS public.exam_periods (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(50) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'active'
  CHECK (status IN ('active','inactive')),
 created_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.exam_sessions
 ADD COLUMN IF NOT EXISTS exam_period_id BIGINT
 REFERENCES public.exam_periods(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS idx_sessions_room_window
 ON public.exam_sessions(room_id,start_time,end_time)
 WHERE status <> 'cancelled';

ALTER TABLE public.exam_periods ENABLE ROW LEVEL SECURITY;
COMMIT;
